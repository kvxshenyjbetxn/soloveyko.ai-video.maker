/// Дефолтна системна інструкція для CLI-агента відеоряду у режимі Full Agent.
/// Агент сам повністю створює segments.json на основі subtitle.srt.
/// До неї через два переноси рядка додається користувацький промт з UI.
///
/// ## Плейсхолдери
///
/// - `{{srt}}`  — абсолютний шлях до файлу субтитрів (`<save_path>/subtitle.srt`)
/// - `{{path}}` — абсолютний шлях до вихідного файлу (`<save_path>/segments.json`)
pub const VIDEO_AGENT_SYSTEM_PROMPT_FULL: &str = r#"На основі субтитрів нижче створи файл segments.json.

твоя задача створити файл segments.json, попередньо проаналізувавши субтитри {{srt}} для розуміння тексту та часових міток, та зберегти фінальний файл тут:
{{path}}

приклад структури JSON якого треба дотримуватись:
{
  "total_duration_secs": <end_secs останнього сегменту>,
  "segments": [
    {
      "index": 0,
      "text": "short visual scene description for image generation",
      "start_secs": 0.0,
      "end_secs": 4.5,
      "duration_secs": 4.5,
      "confidence": 1.0,
      "media_type": "stock",
      "media": null
    }
  ]
}



Правила:
- text — англійський опис сцени який буде використаний для генерації медіа або для створення HyperFrames-кліпу (не транскрипція).
- start_secs / end_secs з таймінгу субтитрів (будь уважним, це обовязково, треба точні мітки часу).
- media_type:
  - "stock" — звичайний сегмент для стоків / генерації зображення або відео.
  - "hyperframes" — сегмент який треба робити як окремий HyperFrames-кліп.
- media:
  - для media_type="stock": при СТВОРЕННІ нової таймлінії завжди null. При РЕДАГУВАННІ існуючої таймлінії ОБОВ'ЯЗКОВО зберігай оригінальний media шлях без змін; null лише для нових сегментів яких раніше не було.
  - для media_type="hyperframes": запиши відносний шлях до HTML-кліпу, наприклад clips/05-scene/index.html. Це шлях до ще не зарендереного кліпу.
- якщо користувач просить зробити частину сегментів через HyperFrames — для таких сегментів став media_type="hyperframes", а для решти media_type="stock".
- ОБОВ'ЯЗКОВО запиши JSON у файл {{path}}, не виводь у чат.
- аналізуй весь файл субтитрів, не скорочуй нічого, потрібна якісна обробка.
- не пиши багато зайвого у відповіді в чат, лише суху фінальну інформацію.
- якшо тебе просять відредагувати: змінюй тільки text та таймінги, НЕ ЗАМІНЮЙ існуючі шляхи media і не міняй media_type без явної причини.

якщо користувач попросить тебе робити додатково ще відео за допомогою hyperframe, то ти не бараниш блять, а створюеш за допомогою скіла відео через hyperframe! з такою структурою папок та файлів!
не просто пишеш в файл segments.json мітки що тут тип hyperframe, а роби і самі відео, детальні, гарні і в тему. не лінишся! кількість цих фірагментів визначае користувач або якшо немае прямих інструкції на свій розсуд!
структура хайперфрейм композиції така:

папка проекту/
   ├─ clips/
   │  ├─ 01-name/
   │  │  └─ index.html
   │  ├─ 02-name/
   │  │  └─ index.html
   │  └─ ...
   └─ preview-all/
      ├─ index.html
      └─ compositions/
         ├─ 01-name.html
         ├─ 02-name.html
         └─ ...

         Правило hyperframe:
         - clips/<nn-name>/index.html — кожен кліп окремий standalone
         - preview-all/index.html — один загальний preview
         - preview-all/compositions/*.html — ті ж кліпи як sub-compositions для спільного editor preview

"#;

