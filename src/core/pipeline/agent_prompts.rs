/// Дефолтна системна інструкція для CLI-агента відеоряду у режимі Full Agent.
/// Агент сам повністю створює segments.json на основі subtitle.srt.
/// До неї через два переноси рядка додається користувацький промт з UI.
///
/// ## Плейсхолдери
///
/// - `{{srt}}`  — абсолютний шлях до файлу субтитрів (`<save_path>/subtitle.srt`)
/// - `{{path}}` — абсолютний шлях до вихідного файлу (`<save_path>/segments.json`)
pub const VIDEO_AGENT_SYSTEM_PROMPT_FULL: &str = r#"На основі субтитрів нижче створи файл segments.json.

твоя задача створити файл segments.json, попередньо проаналізувавши субтитри {{srt}} для розуміння тексту та часових міток, та зберегти фінальний файл тут:
{{path}}

приклад структури JSON якого треба дотримуватись:
{
  "total_duration_secs": <end_secs останнього сегменту>,
  "segments": [
    {
      "index": 0,
      "text": "short visual scene description for image generation",
      "start_secs": 0.0,
      "end_secs": 4.5,
      "duration_secs": 4.5,
      "confidence": 1.0,
      "media": null
    }
  ]
}

Правила:
- text — англійський опис сцени який буде використаний для генерації медіа (не транскрипція).
- start_secs / end_secs з таймінгу субтитрів (будь уважним, це обовязково, треба точні мітки часу).
- media — при СТВОРЕННІ нової таймлінії завжди null. При РЕДАГУВАННІ існуючої таймлінії ОБОВ'ЯЗКОВО зберігай оригінальний media шлях без змін; null лише для нових сегментів яких раніше не було.
- ОБОВ'ЯЗКОВО запиши JSON у файл {{path}}, не виводь у чат.
- аналізуй весь файл субтитрів, не скорочуй нічого, потрібна якісна обробка.
- не пиши багато зайвого у відповіді в чат, лише суху фінальну інформацію.
- якшо тебе просять відредагувати: змінюй тільки text та таймінги, НЕ ЗАМІНЮЙ існуючі шляхи медіа на null.
"#;

